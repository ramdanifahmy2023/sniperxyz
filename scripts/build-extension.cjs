const fs = require('node:fs');
const path = require('node:path');
const directory = path.join(__dirname, '../xyzsniper_extention/assets/js');
// Keep MAIN-world dependencies in one closure, independent of isolated-world scripts.
const output = '// Generated by scripts/build-extension.cjs; edit privacy.js and interceptor.js.\n(() => {\n' +
  ['privacy.js', 'interceptor.js'].map(name => fs.readFileSync(path.join(directory, name), 'utf8')).join('\n') + '\n})();\n';
const target = path.join(directory, 'main-world.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node scripts/build-extension.cjs before testing or publishing.');
} else fs.writeFileSync(target, output);
