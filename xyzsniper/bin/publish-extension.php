<?php

declare(strict_types=1);

$appRoot = dirname(__DIR__);
$sourceDirectory = dirname($appRoot) . '/xyzsniper_extention';
$manifestPath = $sourceDirectory . '/manifest.json';
$changelogPath = $sourceDirectory . '/CHANGELOG.md';
$publicDirectory = $appRoot . '/public/downloads/extensions';
$indexPath = $publicDirectory . '/releases.json';

$scripts = $sourceDirectory . '/assets/js/';
$expectedBundle = "// Generated by scripts/build-extension.cjs; edit privacy.js and interceptor.js.\n(() => {\n"
    . file_get_contents($scripts . 'privacy.js') . "\n" . file_get_contents($scripts . 'interceptor.js') . "\n})();\n";
if (@file_get_contents($scripts . 'main-world.js') !== $expectedBundle) {
    fail('Jalankan node scripts/build-extension.cjs sebelum menerbitkan ekstensi.');
}

function fail(string $message): never
{
    fwrite(STDERR, $message . PHP_EOL);
    exit(1);
}

if (!class_exists(ZipArchive::class)) {
    fail('Ekstensi PHP zip harus aktif untuk menerbitkan paket ekstensi.');
}

$manifest = json_decode((string) @file_get_contents($manifestPath), true);
if (!is_array($manifest) || empty($manifest['version'])) {
    fail('Versi ekstensi tidak ditemukan di manifest.json.');
}

$version = (string) $manifest['version'];
if (!preg_match('/^\d+(?:\.\d+){1,3}$/', $version)) {
    fail('Versi manifest harus menggunakan satu sampai empat angka, misalnya 1.2.0.');
}

$changelog = @file_get_contents($changelogPath);
if ($changelog === false) {
    fail('Buat xyzsniper_extention/CHANGELOG.md sebelum menerbitkan versi.');
}

$sectionPattern = '/^##\s+\[?' . preg_quote($version, '/') . '\]?\s*(?:[-–—]\s*(\d{4}-\d{2}-\d{2}))?\s*\R(.*?)(?=^##\s|\z)/ms';
if (!preg_match($sectionPattern, $changelog, $section)) {
    fail('Tambahkan bagian changelog untuk versi ' . $version . ' di bagian paling atas CHANGELOG.md.');
}

$changes = [];
foreach (preg_split('/\R/', trim($section[2])) as $line) {
    if (preg_match('/^\s*[-*]\s+(.+?)\s*$/', $line, $change)) {
        $changes[] = $change[1];
    }
}
if (!$changes) {
    fail('Bagian changelog versi ' . $version . ' harus berisi setidaknya satu butir perubahan.');
}

$existing = is_file($indexPath) ? json_decode((string) file_get_contents($indexPath), true) : ['releases' => []];
if (!is_array($existing) || !is_array($existing['releases'] ?? null)) {
    fail('Indeks rilis rusak; penerbitan dibatalkan agar riwayat tidak tertimpa.');
}
foreach ($existing['releases'] as $release) {
    if (($release['version'] ?? null) === $version) {
        fail('Versi ' . $version . ' sudah pernah diterbitkan. Naikkan nomor versi sebelum merilis.');
    }
}

$versionDirectory = $publicDirectory . '/' . $version;
if (file_exists($versionDirectory)) {
    fail('Direktori rilis ' . $version . ' sudah ada; arsip versi lama tidak akan ditimpa.');
}

$archiveName = 'xyz-sniper-chrome-extension-' . $version . '.zip';
$relativeArchive = 'downloads/extensions/' . $version . '/' . $archiveName;
$archiveDirectory = $versionDirectory;
$archivePath = $archiveDirectory . '/' . $archiveName;
if (!mkdir($archiveDirectory, 0775, true) && !is_dir($archiveDirectory)) {
    fail('Tidak dapat membuat direktori rilis ' . $version . '.');
}

$zip = new ZipArchive();
if ($zip->open($archivePath, ZipArchive::CREATE | ZipArchive::EXCL) !== true) {
    fail('Tidak dapat membuat arsip ekstensi.');
}

$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($sourceDirectory, FilesystemIterator::SKIP_DOTS),
    RecursiveIteratorIterator::LEAVES_ONLY
);
$root = rtrim($sourceDirectory, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR;
foreach ($iterator as $fileInfo) {
    if (!$fileInfo->isFile()) {
        continue;
    }
    $name = $fileInfo->getFilename();
    if ($name === '.DS_Store' || str_starts_with($name, '._') || str_starts_with($name, '.')) {
        continue;
    }
    $filePath = $fileInfo->getPathname();
    $relativePath = substr($filePath, strlen($root));
    $zip->addFile($filePath, $relativePath);
}

if (!$zip->close()) {
    @unlink($archivePath);
    @rmdir($archiveDirectory);
    fail('Tidak dapat menyelesaikan arsip ekstensi.');
}

$release = [
    'version' => $version,
    'published_at' => $section[1] !== '' ? $section[1] : date('Y-m-d'),
    'file' => $relativeArchive,
    'sha256' => hash_file('sha256', $archivePath),
    'changelog' => $changes,
];
$releases = array_merge([$release], $existing['releases']);
$encodedIndex = json_encode(['releases' => $releases], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
if ($encodedIndex === false || file_put_contents($indexPath . '.tmp', $encodedIndex . PHP_EOL, LOCK_EX) === false || !rename($indexPath . '.tmp', $indexPath)) {
    @unlink($archivePath);
    @rmdir($archiveDirectory);
    @unlink($indexPath . '.tmp');
    fail('Tidak dapat memperbarui indeks rilis.');
}

fwrite(STDOUT, 'Rilis ' . $version . ' diterbitkan: ' . $relativeArchive . PHP_EOL);
